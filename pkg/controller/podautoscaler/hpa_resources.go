var errInvalidHPABounds = errors.New("invalid HPA replica bounds")

// podAutoscalerKind is the Kind recorded in the owner reference of every HPA
// generated by makeHPA. filterHPAObject matches on it to map an HPA event back
// to its PodAutoscaler, so both sides must use this constant.
const podAutoscalerKind = "PodAutoscaler"

// MakeHPA creates an HPA resource from a PodAutoscaler resource.
func makeHPA(pa *pav1.PodAutoscaler, scalingContext scalingctx.ScalingContext) (*autoscalingv2.HorizontalPodAutoscaler, error) {
	return makeHPAWithBounds(pa, scalingContext, paschedules.BaseBounds(pa))
}

func makeHPAWithBounds(pa *pav1.PodAutoscaler, scalingContext scalingctx.ScalingContext, bounds paschedules.Bounds) (*autoscalingv2.HorizontalPodAutoscaler, error) {
	minReplicas, maxReplicas := bounds.MinReplicas, bounds.MaxReplicas
	if maxReplicas == 0 {
		maxReplicas = math.MaxInt32 // Set default to no upper limit if not specified
	}

	hpa := &autoscalingv2.HorizontalPodAutoscaler{
		ObjectMeta: metav1.ObjectMeta{
			Name:        fmt.Sprintf("%s-hpa", pa.Name),
			Namespace:   pa.Namespace,
			Labels:      pa.Labels,
			Annotations: pa.Annotations,
			OwnerReferences: []metav1.OwnerReference{
				*metav1.NewControllerRef(pa, pav1.GroupVersion.WithKind(podAutoscalerKind)),
			},
		},
		Spec: autoscalingv2.HorizontalPodAutoscalerSpec{
			ScaleTargetRef: autoscalingv2.CrossVersionObjectReference{
				APIVersion: pa.Spec.ScaleTargetRef.APIVersion,
				Kind:       pa.Spec.ScaleTargetRef.Kind,
				Name:       pa.Spec.ScaleTargetRef.Name,
			},
			MaxReplicas: maxReplicas,
			Behavior:    buildHPABehavior(scalingContext),
		},
	}
	if minReplicas > 0 {
		hpa.Spec.MinReplicas = &minReplicas
		// if minReplicas exist, check validation of minReplicas and maxReplicas
		if maxReplicas < minReplicas {
			return nil, fmt.Errorf("%w: HPA Strategy: maxReplicas %d must be equal or larger than minReplicas %d", errInvalidHPABounds, maxReplicas, minReplicas)
		}
	}

	hpa.Spec.Metrics = []autoscalingv2.MetricSpec{}
	sources := pa.Spec.MetricsSources
	if len(sources) == 0 {
		return nil, fmt.Errorf("HPA Strategy: no metric source is specified")
	}

	for _, source := range sources {
		if targetValue, err := pametrics.ParseHPATargetValue(source.TargetValue, source.TargetMetric); err != nil {
			return nil, fmt.Errorf("failed to parse target value of the metric source: %w", err)
		} else {
			klog.V(4).InfoS("Creating HPA", "metric", source.TargetMetric, "target", targetValue)

			switch strings.ToLower(source.TargetMetric) {
			case pav1.CPU:
				cpu := int32(math.Ceil(targetValue))
				hpa.Spec.Metrics = append(hpa.Spec.Metrics, autoscalingv2.MetricSpec{
					Type: autoscalingv2.ResourceMetricSourceType,
					Resource: &autoscalingv2.ResourceMetricSource{
						Name: corev1.ResourceCPU,
						Target: autoscalingv2.MetricTarget{
							Type:               autoscalingv2.UtilizationMetricType,
							AverageUtilization: &cpu,
						},
					},
				})

			case pav1.Memory:
				memory := resource.NewQuantity(int64(math.Ceil(targetValue))*1024*1024, resource.BinarySI)
				hpa.Spec.Metrics = append(hpa.Spec.Metrics, autoscalingv2.MetricSpec{
					Type: autoscalingv2.ResourceMetricSourceType,
					Resource: &autoscalingv2.ResourceMetricSource{
						Name: corev1.ResourceMemory,
						Target: autoscalingv2.MetricTarget{
							Type:         autoscalingv2.AverageValueMetricType,
							AverageValue: memory,
						},
					},
				})

			default:
				// AverageValue is a Quantity, so it can carry a fractional target exactly. A
				// fraction such as gpu_cache_usage_perc's 0.5 must not round up to a whole
				// number: a target of 1 for a 0-1 metric means the HPA never scales up.
				// Whole numbers keep the exact int64 Quantity, which a decimal string can't
				// carry near the int64 limit.
				targetQuantity := resource.NewQuantity(int64(targetValue), resource.DecimalSI)
				if targetValue != math.Trunc(targetValue) {
					fractional, err := resource.ParseQuantity(strconv.FormatFloat(targetValue, 'f', -1, 64))
					if err != nil {
						return nil, fmt.Errorf("failed to convert target value %v of metric %s to a quantity: %w", targetValue, source.TargetMetric, err)
					}
					targetQuantity = &fractional
				}
				hpa.Spec.Metrics = append(hpa.Spec.Metrics, autoscalingv2.MetricSpec{
					Type: autoscalingv2.PodsMetricSourceType,
					Pods: &autoscalingv2.PodsMetricSource{
						Metric: autoscalingv2.MetricIdentifier{
							Name: source.TargetMetric,
						},
						Target: autoscalingv2.MetricTarget{
							Type:         autoscalingv2.AverageValueMetricType,
							AverageValue: targetQuantity,
						},
					},
				})
			}
		}
	}

	return hpa, nil
}

// hpaMatchesDesired reports whether the stored HPA already carries everything
// makeHPA would set, so that updating it would change nothing.
func hpaMatchesDesired(existing, desired *autoscalingv2.HorizontalPodAutoscaler) bool {
	return apiequality.Semantic.DeepEqual(existing.Labels, desired.Labels) &&
		apiequality.Semantic.DeepEqual(existing.Annotations, desired.Annotations) &&
		apiequality.Semantic.DeepEqual(existing.OwnerReferences, desired.OwnerReferences) &&
		apiequality.Semantic.DeepEqual(comparableHPASpec(existing.Spec), comparableHPASpec(desired.Spec))
}

// comparableHPASpec returns a copy of spec with the values the API server fills
// in for the fields makeHPA leaves unset. Without it a stored HPA would never
// compare equal to the desired one.
func comparableHPASpec(spec autoscalingv2.HorizontalPodAutoscalerSpec) *autoscalingv2.HorizontalPodAutoscalerSpec {
	out := spec.DeepCopy()
	if out.MinReplicas == nil {
		out.MinReplicas = ptr.To(int32(1))
	}
	// makeHPA sends no policies with a Disabled select policy and the API server
	// stores its default ones. They have no effect while scaling is disabled.
	if out.Behavior != nil {
		for _, rules := range []*autoscalingv2.HPAScalingRules{out.Behavior.ScaleUp, out.Behavior.ScaleDown} {
			if rules != nil && rules.SelectPolicy != nil && *rules.SelectPolicy == autoscalingv2.DisabledPolicySelect {
				rules.Policies = nil
			}
		}
	}
	return out
}

// policyPercent converts the change a scale rate allows, as a fraction of the current
// replicas, to an HPA percent policy value. It rounds down, so the policy never allows
// more than the rate, after absorbing the float error in fractions such as 1.2-1, which is
// 0.19999999999999996 and would otherwise truncate to 19. HPA policy values must be
// positive, so a rate just above 1 still allows 1%, and an int32, so a huge rate is capped
// at math.MaxInt32 instead of overflowing.
func policyPercent(fraction float64) int32 {
	return int32(min(max(math.Floor(fraction*100+1e-9), 1), math.MaxInt32))
}

// buildHPABehavior creates HPA behavior configuration from ScalingContext
func buildHPABehavior(scalingContext scalingctx.ScalingContext) *autoscalingv2.HorizontalPodAutoscalerBehavior {
	// Extract configuration from ScalingContext (single source of truth)
	scaleUpStabilization := int32(scalingContext.GetScaleUpCooldownWindow().Seconds())
	scaleDownStabilization := int32(scalingContext.GetScaleDownCooldownWindow().Seconds())
	maxScaleUpRate := scalingContext.GetMaxScaleUpRate()
	maxScaleDownRate := scalingContext.GetMaxScaleDownRate()

	// Convert rate to percent for K8s HPA
	// max-scale-up-rate: 2.0 means "can double" -> 100% increase
	var scaleUpPercent int32
	if maxScaleUpRate < 1 {
		klog.Warningf("max-scale-up-rate is %f, which is invalid (must be >= 1.0). Defaulting scale-up percentage to 100%%.", maxScaleUpRate)
		scaleUpPercent = 100 // Minimum 100% to allow scaling
	} else {
		scaleUpPercent = policyPercent(maxScaleUpRate - 1.0)
	}

	// max-scale-down-rate: 2.0 means "can halve" -> 50% decrease
	var scaleDownPercent int32
	if maxScaleDownRate < 1 {
		klog.Warningf("max-scale-down-rate is %f, which is invalid (must be >= 1.0). Defaulting scale-down percentage to 100%%.", maxScaleDownRate)
		scaleDownPercent = 100 // Minimum 100% to allow scaling
	} else {
		scaleDownPercent = policyPercent(1.0 - 1.0/maxScaleDownRate)
	}

	// Build behavior spec
	maxPolicy := autoscalingv2.MaxChangePolicySelect
	minPolicy := autoscalingv2.MinChangePolicySelect
	periodSeconds := int32(60)

	behavior := &autoscalingv2.HorizontalPodAutoscalerBehavior{
		ScaleUp: &autoscalingv2.HPAScalingRules{
			StabilizationWindowSeconds: &scaleUpStabilization,
			SelectPolicy:               &maxPolicy,
			Policies: []autoscalingv2.HPAScalingPolicy{
				{
					Type:          autoscalingv2.PercentScalingPolicy,
					Value:         scaleUpPercent,
					PeriodSeconds: periodSeconds,
				},
			},
		},
		ScaleDown: &autoscalingv2.HPAScalingRules{
			StabilizationWindowSeconds: &scaleDownStabilization,
			SelectPolicy:               &minPolicy,
			Policies: []autoscalingv2.HPAScalingPolicy{
				{
					Type:          autoscalingv2.PercentScalingPolicy,
					Value:         scaleDownPercent,
					PeriodSeconds: periodSeconds,
				},
			},
		},
	}

	// A rate of one forbids scaling; HPA policy values must be positive.
	disabledPolicy := autoscalingv2.DisabledPolicySelect
	if maxScaleUpRate == 1 {
		behavior.ScaleUp.SelectPolicy = &disabledPolicy
		behavior.ScaleUp.Policies = nil
	}
	if maxScaleDownRate == 1 {
		behavior.ScaleDown.SelectPolicy = &disabledPolicy
		behavior.ScaleDown.Policies = nil
	}

	klog.V(4).InfoS("Built HPA behavior",
		"scaleUpStabilization", scaleUpStabilization,
		"scaleDownStabilization", scaleDownStabilization,
		"scaleUpPercent", scaleUpPercent,
		"scaleDownPercent", scaleDownPercent)

	return behavior
}
